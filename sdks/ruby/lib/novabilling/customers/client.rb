      # Retrieve a paginated list of customers. Supports filtering by search term, country, and currency.
      #
      # @param request_options [Hash]
      # @param params [Hash]
      # @option request_options [String] :base_url
      # @option request_options [Hash{String => Object}] :additional_headers
      # @option request_options [Hash{String => Object}] :additional_query_parameters
      # @option request_options [Hash{String => Object}] :additional_body_parameters
      # @option request_options [Integer] :timeout_in_seconds
      # @option params [Integer, nil] :page
      # @option params [Integer, nil] :limit
      # @option params [String, nil] :search
      # @option params [String, nil] :country
      # @option params [String, nil] :currency
      # @option params [String, nil] :sort_by
      # @option params [Novabilling::Customers::Types::ListCustomersRequestSortOrder, nil] :sort_order
      #
      # @return [Novabilling::Types::PaginatedCustomerResponse]
      def list(request_options: {}, **params)
        params = Novabilling::Internal::Types::Utils.normalize_keys(params)
        query_param_names = %i[page limit search country currency sort_by sort_order]
        query_params = {}
        query_params["page"] = params[:page] if params.key?(:page)
        query_params["limit"] = params[:limit] if params.key?(:limit)
        query_params["search"] = params[:search] if params.key?(:search)
        query_params["country"] = params[:country] if params.key?(:country)
        query_params["currency"] = params[:currency] if params.key?(:currency)
        query_params["sortBy"] = params[:sort_by] if params.key?(:sort_by)
        query_params["sortOrder"] = params[:sort_order] if params.key?(:sort_order)
        params.except(*query_param_names)

        request = Novabilling::Internal::JSON::Request.new(
          base_url: request_options[:base_url],
          method: "GET",
          path: "api/customers",
          query: query_params,
          request_options: request_options
        )
        begin
          response = @client.send(request)
        rescue Net::HTTPRequestTimeout
          raise Novabilling::Errors::TimeoutError
        end
        code = response.code.to_i
        if code.between?(200, 299)
          Novabilling::Types::PaginatedCustomerResponse.load(response.body)
        else
          error_class = Novabilling::Errors::ResponseError.subclass_for_code(code)
          raise error_class.new(response.body, code: code)
        end
      end

