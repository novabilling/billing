    /// <summary>
    /// Create a new tenant account with a company name. This provisions an isolated database, generates an API key, and returns JWT tokens.
    /// </summary>
    /// <example><code>
    /// await client.Auth.RegisterAsync(
    ///     new RegisterDto
    ///     {
    ///         Name = "John Doe",
    ///         Email = "john@company.com",
    ///         Password = "securePassword123",
    ///         CompanyName = "Acme Corp",
    ///     }
    /// );
    /// </code></example>
    public WithRawResponseTask<RegisterResponse> RegisterAsync(
        RegisterDto request,
        RequestOptions? options = null,
        CancellationToken cancellationToken = default
    )
    {
        return new WithRawResponseTask<RegisterResponse>(
            RegisterAsyncCore(request, options, cancellationToken)
        );
    }

